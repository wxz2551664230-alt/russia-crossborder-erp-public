const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('../frontend/node_modules/typescript');
const source = fs.readFileSync(path.join(__dirname, '../frontend/src/amazonValidation.ts'), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText;
const moduleValue = {exports: {}};
new Function('exports', 'module', compiled)(moduleValue.exports, moduleValue);
const {keywordReferenceError, keywordReferenceLength, amazonRequestError} = moduleValue.exports;
assert.equal(keywordReferenceLength('浴帘🌲'), 3);
assert.equal(keywordReferenceError('浴帘🌲'.repeat(6666) + 'ab', 20000), '');
assert.match(keywordReferenceError('浴帘🌲'.repeat(6667), 20000), /20001.*20000/);
assert.equal(keywordReferenceError('', 20000), '');
const invalid = details => ({code: 'validation_error', message: '提交的数据不完整或格式不正确', details});
assert.match(amazonRequestError(invalid([{loc: ['body', 'keywords'], type: 'string_too_long'}]), 18000), /本批关键词.*18000/);
assert.match(amazonRequestError(invalid([{loc: ['body', 'keywords'], type: 'string_too_long', msg: 'String should have at most 200 characters'}])), /类目搜索关键词.*200/);
assert.match(amazonRequestError(invalid([{loc: ['body', 'keywords'], type: 'string_too_long', msg: 'String should have at most 1500 characters'}])), /本批关键词.*1500/);
assert.match(amazonRequestError(invalid([{loc: ['body', 'quantity'], type: 'int_from_float'}])), /可售库存.*整数/);
assert.match(amazonRequestError(invalid([{loc: ['body', 'items', 2, 'variant_id'], type: 'string_pattern_mismatch'}])), /第 3 个规格的规格.*格式/);
assert.equal(amazonRequestError(invalid([{loc: ['body', 'shipping_template'], type: 'missing'}])), '请填写FBM 配送模板');
assert.equal(amazonRequestError({code: 'conflict', message: '原电脑离线'}), '原电脑离线');
assert.equal(amazonRequestError(null), '操作未完成');
assert.equal(amazonRequestError(invalid([])), '提交的数据不完整或格式不正确');
console.log('Amazon keyword length and actionable validation messages passed');
